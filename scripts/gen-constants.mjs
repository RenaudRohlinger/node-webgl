#!/usr/bin/env node
// Generates src/webgl/constants.ts from the Khronos WebGL IDL files in scripts/idl/.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
function parse(file) {
  const src = readFileSync(join(root, 'scripts/idl', file), 'utf8');
  const out = [];
  const re = /const\s+GL\w+\s+(\w+)\s*=\s*(-?0x[0-9A-Fa-f]+|-?\d+)\s*;/g;
  let m;
  while ((m = re.exec(src))) out.push([m[1], m[2]]);
  return out;
}
const v1 = parse('webgl1.idl');
const v2 = parse('webgl2.idl');
const seen = new Set(v1.map(([n]) => n));
const v2only = v2.filter(([n]) => !seen.has(n));
const fmt = (list) => list.map(([n, v]) => `  ${n}: ${v},`).join('\n');
let ts = `// GENERATED by scripts/gen-constants.mjs from the Khronos WebGL IDL — do not edit.\n\n`;
ts += `/** Constants exposed on every WebGLRenderingContext (WebGL 1). */\nexport const WEBGL1_CONSTANTS = {\n${fmt(v1)}\n} as const;\n\n`;
ts += `/** Constants that WebGL 2 adds on top of WebGL 1. */\nexport const WEBGL2_CONSTANTS = {\n${fmt(v2only)}\n} as const;\n\n`;
ts += `/** All WebGL 1 + 2 constants, for internal use. */\nexport const GL = { ...WEBGL1_CONSTANTS, ...WEBGL2_CONSTANTS } as const;\nexport type GLConstantName = keyof typeof GL;\n`;
writeFileSync(join(root, 'src/webgl/constants.ts'), ts);
console.log(`constants: ${v1.length} WebGL1, ${v2only.length} WebGL2-only`);
